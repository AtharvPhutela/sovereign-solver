#!/usr/bin/env python3
"""Fetch and verify benchmark corpora -- Build Map ticket #2, gate M0.

    fetch_corpus.py                     # pull the default sets (netlib_lp)
    fetch_corpus.py --set miplib2017    # pull a deferred set
    fetch_corpus.py --list              # show sets and local status
    fetch_corpus.py --verify            # re-hash local files against the lock
    fetch_corpus.py --clean netlib_lp   # remove a downloaded set

Design points:

* Downloaded data goes to benchmarks/data/<set>/ which is gitignored. Only
  benchmarks/smoke/ is version-controlled.
* Every downloaded artefact is recorded with its sha256 in
  benchmarks/data/<set>/_lock.toml, so `--verify` can prove the local corpus
  matches what was fetched, and a CI cache can be trusted.
* Netlib instances arrive in a packed format and are expanded to MPS by `emps`,
  a tiny standalone C decompressor built into benchmarks/.tools/. emps has no
  optimization logic; it is a file-format expander (see sovereignty.toml).
* stdlib only -- urllib, no requests.
"""

from __future__ import annotations

import argparse
import hashlib
import re
import shutil
import subprocess
import sys
import tomllib
import urllib.error
import urllib.request
from pathlib import Path

HERE = Path(__file__).resolve().parent
MANIFEST = HERE / "corpus.toml"
USER_AGENT = "sovereign-solver-corpus-fetch/1 (+ticket-2)"
TIMEOUT = 60


# --------------------------------------------------------------------------
# small helpers
# --------------------------------------------------------------------------

def load_manifest() -> dict:
    with MANIFEST.open("rb") as fh:
        m = tomllib.load(fh)
    if m.get("schema_version") != 1:
        sys.exit(f"corpus.toml: unsupported schema_version {m.get('schema_version')!r}")
    return m


def data_dir(m: dict) -> Path:
    return (HERE / m["meta"]["data_dir"]).resolve()


def tools_dir(m: dict) -> Path:
    d = (HERE / m["meta"]["tools_dir"]).resolve()
    d.mkdir(parents=True, exist_ok=True)
    return d


def sha256(path: Path) -> str:
    h = hashlib.sha256()
    with path.open("rb") as fh:
        for chunk in iter(lambda: fh.read(1 << 20), b""):
            h.update(chunk)
    return h.hexdigest()


def download(url: str, dest: Path, *, quiet: bool = False) -> Path:
    dest.parent.mkdir(parents=True, exist_ok=True)
    req = urllib.request.Request(url, headers={"User-Agent": USER_AGENT})
    try:
        with urllib.request.urlopen(req, timeout=TIMEOUT) as resp:
            body = resp.read()
    except urllib.error.URLError as exc:
        raise SystemExit(f"download failed: {url}\n  {exc}")
    dest.write_bytes(body)
    if not quiet:
        print(f"  got {dest.name:<24} {len(body):>10,} B")
    return dest


def write_lock(set_dir: Path, entries: dict[str, dict]) -> None:
    lines = [
        "# Auto-generated by fetch_corpus.py. Records what was downloaded and the",
        "# sha256 of each expanded instance, so --verify can prove the local copy",
        "# is intact. Do not edit by hand.",
        "",
        "schema_version = 1",
        "",
    ]
    for name in sorted(entries):
        e = entries[name]
        lines.append(f"[instances.{name}]")
        for k, v in e.items():
            if isinstance(v, str):
                lines.append(f'{k} = "{v}"')
            elif isinstance(v, float):
                lines.append(f"{k} = {v!r}")
            else:
                lines.append(f"{k} = {v}")
        lines.append("")
    (set_dir / "_lock.toml").write_text("\n".join(lines))


def read_lock(set_dir: Path) -> dict:
    lock = set_dir / "_lock.toml"
    if not lock.is_file():
        return {}
    with lock.open("rb") as fh:
        return tomllib.load(fh).get("instances", {})


# --------------------------------------------------------------------------
# emps -- the Netlib packed-format decoder
# --------------------------------------------------------------------------

def ensure_emps(m: dict, netlib_cfg: dict) -> Path:
    """Download and compile emps once; return the executable path."""
    tools = tools_dir(m)
    exe = tools / "emps"
    if exe.is_file():
        return exe

    cc = shutil.which("cc") or shutil.which("gcc") or shutil.which("clang")
    if not cc:
        sys.exit("no C compiler (cc/gcc/clang) found; cannot build the emps decoder")

    src = tools / "emps.c"
    if not src.is_file():
        print("building the Netlib decoder (emps)...")
        download(netlib_cfg["decoder_source"], src)

    # emps.c is K&R-ish; -w silences the ancient-style warnings. It is a pure
    # decompressor -- no math libs, no optimization code.
    proc = subprocess.run(
        [cc, "-O2", "-w", "-o", str(exe), str(src)],
        capture_output=True, text=True,
    )
    if proc.returncode != 0:
        sys.exit(f"emps build failed:\n{proc.stdout}\n{proc.stderr}")
    print(f"  emps -> {exe}")
    return exe


def _is_shar(packed: Path) -> bool:
    head = packed.read_bytes()[:64]
    return head.startswith(b"#") and b"unbundle" in head


def emps_expand(emps: Path, packed: Path, mps_out: Path) -> None:
    # A handful of the larger Netlib problems (stocfor3, truss, ...) are shipped
    # as shell-archive bundles rather than a raw packed file: the bundle must be
    # unpacked with `sh` first. Not worth the extra machinery for M0 -- these are
    # recorded as a known gap in corpus.toml. Fail loudly rather than write a
    # half-file.
    if _is_shar(packed):
        raise RuntimeError("shar-bundled instance (needs `sh` unpack before emps); skipped for M0")
    with packed.open("rb") as fin, mps_out.open("wb") as fout:
        proc = subprocess.run([str(emps)], stdin=fin, stdout=fout,
                              stderr=subprocess.PIPE)
    ok = proc.returncode == 0 and mps_out.stat().st_size > 0
    if not ok:
        mps_out.unlink(missing_ok=True)          # never leave a 0-byte orphan
        raise RuntimeError(f"emps failed on {packed.name}: "
                           f"{proc.stderr.decode(errors='replace').strip()[:200]}")


# --------------------------------------------------------------------------
# Netlib readme -> reference objective values + instance list
# --------------------------------------------------------------------------

_SUMMARY_ROW = re.compile(
    r"^([A-Z0-9][A-Z0-9._-]*)\s+(\d+)\s+(\d+)\s+"      # name rows cols
    r"([\d,]+)\s+"                                      # nonzeros (may have (see NOTES))
    r".*?([+-]?\d(?:\.\d+)?[Ee][+-]?\d+)"              # optimal value in sci notation
)
_CPLEX_ROW = re.compile(r"^([A-Z0-9][A-Z0-9._-]*)\s+([+-]?\d(?:\.\d+)?[Ee][+-]?\d+)\s*$")


def parse_netlib_reference(readme_text: str) -> dict[str, dict]:
    """Extract {NAME: {rows, cols, nonzeros, optimal_value, ...}} from the readme."""
    out: dict[str, dict] = {}
    in_summary = False
    for line in readme_text.splitlines():
        if "PROBLEM SUMMARY TABLE" in line:
            in_summary = True
            continue
        if not in_summary:
            continue
        if line.strip().startswith("BOUND-TYPE TABLE") or line.startswith("NOTES"):
            in_summary = False
            continue
        mrow = _SUMMARY_ROW.match(line.strip())
        if mrow:
            name, rows, cols, nz, opt = mrow.groups()
            out[name.lower()] = {
                "rows": int(rows),
                "cols": int(cols),
                "nonzeros": int(nz.replace(",", "")),
                "optimal_value": float(opt),
                "optimal_source": "netlib readme (MINOS 5.3, Sept 1988)",
            }
    # The readme then lists CPLEX values that differ; capture as a cross-check.
    tail = readme_text.split("PROBLEM SUMMARY TABLE", 1)[-1]
    if "CPLEX" in tail:
        cplex_block = tail.split("CPLEX", 1)[-1]
        for line in cplex_block.splitlines()[:120]:
            mc = _CPLEX_ROW.match(line.strip())
            if mc and mc.group(1).lower() in out:
                out[mc.group(1).lower()]["optimal_value_cplex"] = float(mc.group(2))
    return out


def scrape_instance_names(index_html: str, exclude: list[str]) -> list[str]:
    names = re.findall(r'href="([^"/]+)"', index_html)
    ex = set(exclude)
    keep = []
    for n in names:
        if n in ex or "." in n or n.startswith("mail") or n.lower() == n and not n[0].isalnum():
            # Netlib packed instances have no extension; anything with a dot
            # (emps.c, emps.exe.gz, index.html) is tooling, not an instance.
            continue
        keep.append(n)
    return sorted(set(keep))


# --------------------------------------------------------------------------
# per-set fetchers
# --------------------------------------------------------------------------

def fetch_netlib(m: dict, cfg: dict, *, include_kennington: bool) -> None:
    set_dir = data_dir(m) / cfg["dest"]
    set_dir.mkdir(parents=True, exist_ok=True)
    emps = ensure_emps(m, cfg)

    print("fetching Netlib LP index and reference values...")
    readme = download(cfg["index_url"], tools_dir(m) / "netlib_readme", quiet=True).read_text(
        encoding="utf-8", errors="replace")
    reference = parse_netlib_reference(readme)
    print(f"  parsed {len(reference)} reference objective values")

    index_html = download(cfg["base_url"], tools_dir(m) / "netlib_index.html", quiet=True).read_text(
        encoding="utf-8", errors="replace")
    names = scrape_instance_names(index_html, cfg.get("index_exclude", []))
    print(f"  {len(names)} packed instances listed")

    lock: dict[str, dict] = {}
    failures: list[str] = []
    for i, name in enumerate(names, 1):
        packed = tools_dir(m) / f"_packed_{name}"
        mps = set_dir / f"{name}.mps"
        try:
            download(cfg["base_url"] + name, packed, quiet=True)
            emps_expand(emps, packed, mps)
        except Exception as exc:                     # noqa: BLE001 -- report, continue
            failures.append(f"{name}: {exc}")
            print(f"  [{i:>3}/{len(names)}] {name:<16} FAILED ({exc})")
            continue
        finally:
            packed.unlink(missing_ok=True)

        ref = reference.get(name, {})
        lock[name] = {
            "file": mps.name,
            "sha256": sha256(mps),
            "bytes": mps.stat().st_size,
            **({"optimal_value": ref["optimal_value"]} if "optimal_value" in ref else {}),
            **({"rows": ref["rows"], "cols": ref["cols"], "nonzeros": ref["nonzeros"]}
               if "rows" in ref else {}),
        }
        print(f"  [{i:>3}/{len(names)}] {name:<16} ok  "
              f"{'obj=' + repr(ref['optimal_value']) if 'optimal_value' in ref else '(no ref value)'}")

    if include_kennington:
        print("  (Kennington subset requested -- fetching)")
        _fetch_netlib_kennington(m, cfg, set_dir, emps, reference, lock)

    write_lock(set_dir, lock)
    _write_reference_toml(set_dir, reference)
    print(f"\nNetlib LP: {len(lock)} instances in {set_dir}")
    if failures:
        print(f"  {len(failures)} instance(s) failed -- see below (non-fatal):")
        for f in failures:
            print(f"    {f}")


def _fetch_netlib_kennington(m, cfg, set_dir, emps, reference, lock) -> None:
    try:
        idx = download(cfg["kennington_url"], tools_dir(m) / "kennington_index.html",
                       quiet=True).read_text(errors="replace")
    except SystemExit:
        print("    kennington index unavailable, skipping")
        return
    for name in scrape_instance_names(idx, cfg.get("index_exclude", [])):
        packed = tools_dir(m) / f"_packed_k_{name}"
        mps = set_dir / f"{name}.mps"
        try:
            download(cfg["kennington_url"] + name, packed, quiet=True)
            emps_expand(emps, packed, mps)
            lock[name] = {"file": mps.name, "sha256": sha256(mps),
                          "bytes": mps.stat().st_size, "subset": "kennington"}
            print(f"    kennington/{name:<14} ok")
        except Exception as exc:                     # noqa: BLE001
            print(f"    kennington/{name:<14} FAILED ({exc})")
        finally:
            packed.unlink(missing_ok=True)


def _write_reference_toml(set_dir: Path, reference: dict[str, dict]) -> None:
    lines = [
        "# Reference optimal objective values for Netlib LP, parsed from",
        "# https://www.netlib.org/lp/data/readme (MINOS 5.3 values; a few CPLEX",
        "# cross-check values where the readme records a discrepancy).",
        "#",
        "# This is an oracle-rule reference: an independent published answer, not",
        "# a value this project computed. Auto-generated -- do not edit.",
        "",
        "schema_version = 1",
        "",
    ]
    for name in sorted(reference):
        r = reference[name]
        lines.append(f"[{name}]")
        for k, v in r.items():
            lines.append(f'{k} = "{v}"' if isinstance(v, str) else f"{k} = {v!r}")
        lines.append("")
    (set_dir / "_reference.toml").write_text("\n".join(lines))


def fetch_deferred_stub(name: str, cfg: dict) -> None:
    print(f"set '{name}' is deferred and not yet implemented in fetch_corpus.py.")
    print(f"  {cfg.get('description', '')}")
    for key in ("homepage", "benchmark_archive", "collection_archive", "archive",
                "solutions_url", "metadata_csv", "instances_csv"):
        if key in cfg:
            print(f"  {key}: {cfg[key]}")
    print("  Licence:", cfg.get("licence", "unknown"))
    print("\n  These sets are large and are not needed until the milestone that")
    print("  consumes them (MIPLIB -> M5, Mittelmann -> M5/M9, MILPBench -> M7).")
    print("  Implement the fetcher for this set when that milestone starts.")


# --------------------------------------------------------------------------
# top-level actions
# --------------------------------------------------------------------------

def action_list(m: dict) -> int:
    dd = data_dir(m)
    print(f"{'set':<24}{'default':<9}{'deferred':<10}{'local':<8}status")
    print("-" * 70)
    for name, cfg in m["sets"].items():
        set_dir = dd / cfg.get("dest", name)
        lock = read_lock(set_dir)
        local = f"{len(lock)}" if lock else "-"
        status = "downloaded" if lock else ("deferred" if cfg.get("deferred") else "not fetched")
        print(f"{name:<24}{str(cfg.get('default', False)):<9}"
              f"{str(cfg.get('deferred', False)):<10}{local:<8}{status}")
    print(f"\ndata dir: {dd}  (gitignored)")
    print("committed: benchmarks/smoke/ (4 instances, see smoke/expected.toml)")
    return 0


def action_verify(m: dict) -> int:
    dd = data_dir(m)
    bad = 0
    checked = 0
    for name, cfg in m["sets"].items():
        set_dir = dd / cfg.get("dest", name)
        lock = read_lock(set_dir)
        if not lock:
            continue
        print(f"verifying {name} ({len(lock)} instances)...")
        for inst, e in lock.items():
            f = set_dir / e["file"]
            checked += 1
            if not f.is_file():
                print(f"  MISSING {inst} ({e['file']})")
                bad += 1
            elif sha256(f) != e["sha256"]:
                print(f"  CHANGED {inst}: sha256 mismatch")
                bad += 1
    if checked == 0:
        print("nothing downloaded to verify.")
        return 0
    print(f"\n{checked - bad}/{checked} instances intact.")
    return 1 if bad else 0


def action_clean(m: dict, target: str) -> int:
    cfg = m["sets"].get(target)
    if not cfg:
        sys.exit(f"unknown set: {target}")
    set_dir = data_dir(m) / cfg.get("dest", target)
    if set_dir.is_dir():
        shutil.rmtree(set_dir)
        print(f"removed {set_dir}")
    else:
        print(f"{set_dir} does not exist")
    return 0


def main(argv: list[str] | None = None) -> int:
    ap = argparse.ArgumentParser(description="Fetch benchmark corpora (ticket #2)")
    ap.add_argument("--set", action="append", dest="sets", metavar="NAME",
                    help="fetch a specific set (repeatable); overrides the defaults")
    ap.add_argument("--list", action="store_true", help="show sets and local status")
    ap.add_argument("--verify", action="store_true", help="re-hash local files against the lock")
    ap.add_argument("--clean", metavar="NAME", help="delete a downloaded set")
    ap.add_argument("--include-kennington", action="store_true",
                    help="also fetch the Netlib Kennington subset")
    args = ap.parse_args(argv)

    m = load_manifest()

    if args.list:
        return action_list(m)
    if args.verify:
        return action_verify(m)
    if args.clean:
        return action_clean(m, args.clean)

    if args.sets:
        wanted = args.sets
    else:
        wanted = [name for name, cfg in m["sets"].items() if cfg.get("default")]
        print(f"fetching default sets: {', '.join(wanted)}")
        print("(deferred sets: run with --set <name>; see --list)\n")

    for name in wanted:
        cfg = m["sets"].get(name)
        if not cfg:
            print(f"unknown set '{name}', skipping")
            continue
        if name == "netlib_lp":
            fetch_netlib(m, cfg, include_kennington=args.include_kennington)
        else:
            fetch_deferred_stub(name, cfg)

    return 0


if __name__ == "__main__":
    sys.exit(main())
